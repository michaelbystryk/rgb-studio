// Builds a release: a portable zip (with Node bundled) and, if Inno Setup is installed, the installer.
//
//   node tools/build-release.js [--no-installer]
//
// Output goes to dist/:  rgb-studio-X.Y.Z.zip, RGBStudioSetup-X.Y.Z.exe, and the staging folder "RGB Studio".
// The version comes from package.json. No dependencies; needs Windows (csc, tar, PowerShell).

import fs from 'node:fs';
import path from 'node:path';
import https from 'node:https';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

// The Node.js build that gets bundled. To bump it:
//   1. Pick an LTS from https://nodejs.org/dist/index.json (the newest LTS line, a few weeks old).
//   2. Set NODE_VERSION.
//   3. Copy the SHA256 of node-v<version>-win-x64.zip from https://nodejs.org/dist/v<version>/SHASUMS256.txt.
const NODE_VERSION = '24.21.0';
const NODE_ZIP_SHA256 = '158f7685b44de51f6c0df1d153526cbcd3e1bc739a8dfc607721cef75de9e541';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const CACHE = path.join(ROOT, '.cache');
const STAGE = path.join(DIST, 'RGB Studio');
// Windows' own bsdtar (reads and writes zip). A tar from Git Bash would treat C: as a host name.
const TAR = path.join(process.env.SystemRoot || 'C:/Windows', 'System32', 'tar.exe');
const noInstaller = process.argv.includes('--no-installer');

const step = (msg) => console.log(`\n==> ${msg}`);
const fail = (msg) => { console.error(`\nERROR: ${msg}`); process.exit(1); };

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: 'inherit', ...opts });
  if (r.error) fail(`could not run ${cmd}: ${r.error.message}`);
  if (r.status !== 0) fail(`${cmd} failed (exit code ${r.status})`);
}

function download(url, dest, redirects = 5) {
  return new Promise((resolve, reject) => {
    https.get(url, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location && redirects > 0) {
        res.resume();
        return resolve(download(new URL(res.headers.location, url).href, dest, redirects - 1));
      }
      if (res.statusCode !== 200) { res.resume(); return reject(new Error(`HTTP ${res.statusCode} for ${url}`)); }
      const out = fs.createWriteStream(dest);
      res.pipe(out);
      out.on('finish', () => out.close(resolve));
      out.on('error', reject);
    }).on('error', reject);
  });
}

const sha256 = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');

function copyInto(rel, destRoot = STAGE) {
  const src = path.join(ROOT, rel);
  if (!fs.existsSync(src)) fail(`missing ${rel}`);
  fs.cpSync(src, path.join(destRoot, rel), { recursive: true });
}

// 1. Version
const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const version = pkg.version;
if (!/^\d+\.\d+\.\d+$/.test(version)) fail(`package.json version "${version}" is not X.Y.Z`);
console.log(`RGB Studio ${version}`);

step('Writing player/Version.cs');
fs.writeFileSync(path.join(ROOT, 'player', 'Version.cs'), [
  '// Generated by tools/build-release.js from package.json. Do not edit by hand.',
  'using System.Reflection;',
  '',
  `[assembly: AssemblyVersion("${version}.0")]`,
  `[assembly: AssemblyFileVersion("${version}.0")]`,
  `[assembly: AssemblyInformationalVersion("${version}")]`,
  '[assembly: AssemblyCompany("Michael Bystryk")]',
  '[assembly: AssemblyProduct("RGB Studio")]',
  '[assembly: AssemblyCopyright("Copyright (c) Michael Bystryk")]',
  '',
].join('\r\n'));

// 2. Node.js
step(`Node.js v${NODE_VERSION} (win-x64)`);
fs.mkdirSync(CACHE, { recursive: true });
const zipName = `node-v${NODE_VERSION}-win-x64.zip`;
const nodeZip = path.join(CACHE, zipName);
if (!fs.existsSync(nodeZip)) {
  const url = `https://nodejs.org/dist/v${NODE_VERSION}/${zipName}`;
  console.log(`downloading ${url}`);
  const part = nodeZip + '.part';
  try { await download(url, part); } catch (e) { fail(`download failed: ${e.message}`); }
  fs.renameSync(part, nodeZip);
} else {
  console.log(`using cached ${path.relative(ROOT, nodeZip)}`);
}
const actual = sha256(nodeZip);
if (actual !== NODE_ZIP_SHA256) {
  fs.rmSync(nodeZip, { force: true });
  fail(`SHA256 mismatch for ${zipName}\n  expected ${NODE_ZIP_SHA256}\n  got      ${actual}\n(the bad download was deleted)`);
}
console.log('SHA256 verified');

const nodeExtract = path.join(CACHE, `node-v${NODE_VERSION}-extract`);
fs.rmSync(nodeExtract, { recursive: true, force: true });
fs.mkdirSync(nodeExtract, { recursive: true });
const inner = `node-v${NODE_VERSION}-win-x64`;
run(TAR, ['-xf', nodeZip, '-C', nodeExtract, `${inner}/node.exe`, `${inner}/LICENSE`]);

// 3. Stage
step('Staging dist/RGB Studio');
fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(path.join(STAGE, 'node'), { recursive: true });
fs.copyFileSync(path.join(nodeExtract, inner, 'node.exe'), path.join(STAGE, 'node', 'node.exe'));
fs.copyFileSync(path.join(nodeExtract, inner, 'LICENSE'), path.join(STAGE, 'node', 'LICENSE'));

for (const f of ['server.js', 'package.json', 'start.cmd', 'README.md', 'LICENSE']) copyInto(f);
for (const d of ['src', 'shared', 'public']) copyInto(d);
fs.mkdirSync(path.join(STAGE, 'docs'));
for (const f of fs.readdirSync(path.join(ROOT, 'docs'))) {
  if (f.endsWith('.md')) fs.copyFileSync(path.join(ROOT, 'docs', f), path.join(STAGE, 'docs', f));
}

// three: the page's import map only uses build/ and examples/jsm/.
const threeSrc = path.join(ROOT, 'node_modules', 'three');
if (!fs.existsSync(path.join(threeSrc, 'build', 'three.module.js'))) {
  fail('node_modules/three is missing. Run "npm install" first.');
}
const threeDst = path.join(STAGE, 'node_modules', 'three');
for (const part of ['build', 'examples/jsm', 'package.json', 'LICENSE']) {
  fs.cpSync(path.join(threeSrc, part), path.join(threeDst, part), { recursive: true });
}

// 4. Exes
step('Building the exes');
const stagePlayer = path.join(STAGE, 'player');
run('cmd.exe', ['/c', path.join(ROOT, 'player', 'build.cmd'), stagePlayer]);
for (const exe of ['RGBStudio.exe', 'RGBStudioPlayer.exe']) {
  if (!fs.existsSync(path.join(stagePlayer, exe))) fail(`build did not produce player/${exe}`);
}

// 5. Zip
step(`Zipping rgb-studio-${version}.zip`);
const zipPath = path.join(DIST, `rgb-studio-${version}.zip`);
run(TAR, ['-a', '-c', '-f', zipPath, '-C', DIST, 'RGB Studio']);
console.log(`${path.relative(ROOT, zipPath)}  ${(fs.statSync(zipPath).size / 1048576).toFixed(1)} MB`);

// 6. Installer
if (noInstaller) {
  console.log('\nSkipping the installer (--no-installer).');
} else {
  step('Building the installer');
  const iscc = findIscc();
  if (!iscc) {
    console.log('Inno Setup 6 was not found, so the installer was skipped.');
    console.log('Install it from https://jrsoftware.org/isinfo.php (or "choco install innosetup") and run this again.');
  } else {
    console.log(`using ${iscc}`);
    run(iscc, [`/DAppVersion=${version}`, `/DSourceDir=${STAGE}`, `/O${DIST}`, path.join(ROOT, 'installer', 'RGBStudio.iss')]);
    const setup = path.join(DIST, `RGBStudioSetup-${version}.exe`);
    if (!fs.existsSync(setup)) fail('Inno Setup finished but the installer is missing');
    console.log(`${path.relative(ROOT, setup)}  ${(fs.statSync(setup).size / 1048576).toFixed(1)} MB`);
  }
}

console.log('\nDone.');

function findIscc() {
  const dirs = (process.env.PATH || '').split(path.delimiter).filter(Boolean);
  for (const base of [process.env['ProgramFiles(x86)'], process.env.ProgramFiles, process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, 'Programs')]) {
    if (base) dirs.push(path.join(base, 'Inno Setup 6'));
  }
  for (const d of dirs) {
    const p = path.join(d, 'ISCC.exe');
    if (fs.existsSync(p)) return p;
  }
  return null;
}
